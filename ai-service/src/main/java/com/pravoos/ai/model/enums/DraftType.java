package com.pravoos.ai.model.enums;

import com.pravoos.ai.exception.DraftTypeNotFoundException;

import java.util.Arrays;

public enum DraftType {

    COMPLAINT(
            "Жалоба",
            "Составь процессуальную жалобу по делу о банкротстве на основании материалов дела. "
                    + "Структура: вводная часть (наименование суда, стороны, реквизиты дела), "
                    + "фактические обстоятельства, правовое обоснование со ссылками на нормы Закона N 127-ФЗ и АПК РФ, "
                    + "просительная часть. Соблюдай требования процессуального законодательства."),

    PETITION(
            "Ходатайство",
            "Составь процессуальное ходатайство по делу о банкротстве на основании материалов дела. "
                    + "Структура: вводная часть (наименование суда, стороны, реквизиты дела), "
                    + "основание обращения со ссылками на нормы АПК РФ и Закона N 127-ФЗ, "
                    + "содержание просьбы. Документ должен быть лаконичным и соответствовать процессуальным требованиям."),

    OBJECTION(
            "Возражение",
            "Составь мотивированное возражение по делу о банкротстве на основании материалов дела. "
                    + "Структура: предмет возражения, обоснование фактических обстоятельств, "
                    + "правовые доводы со ссылками на Закон N 127-ФЗ, АПК РФ и судебную практику, "
                    + "просительная часть. Возражение должно опровергать доводы процессуального оппонента."),

    APPEAL(
            "Апелляционная жалоба",
            "Составь апелляционную жалобу на судебный акт по делу о банкротстве на основании материалов дела. "
                    + "Структура: наименование суда апелляционной инстанции, сведения о решении и заявителе, "
                    + "доводы о незаконности/необоснованности решения со ссылками на нормы АПК РФ и материального права, "
                    + "просительная часть. Укажи конкретные основания для отмены (ст. 270 АПК РФ)."),

    STATEMENT(
            "Исковое заявление",
            "Составь исковое заявление в рамках дела о банкротстве на основании материалов дела. "
                    + "Структура: наименование суда, стороны, цена иска, обстоятельства дела, "
                    + "правовое обоснование со ссылками на Закон N 127-ФЗ и ГК РФ, "
                    + "требования, перечень приложений. Соблюдай требования ст. 125 АПК РФ.");

    private final String displayName;
    private final String instruction;

    DraftType(String displayName, String instruction) {
        this.displayName = displayName;
        this.instruction = instruction;
    }

    public String displayName() {
        return displayName;
    }

    public String instruction() {
        return instruction;
    }

    public static DraftType fromId(String id) {
        return Arrays.stream(values())
                .filter(type -> type.name().equalsIgnoreCase(id))
                .findFirst()
                .orElseThrow(() -> new DraftTypeNotFoundException(id));
    }
}
